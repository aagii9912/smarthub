-- Утсаар харилцагч хайх индекс.
--
-- Хоёр шинэ зам утсаар харилцагч хайдаг болсон:
--   1) `recordCommentLead` — сэтгэгдлээс барьсан утсыг байгаа харилцагчтай
--      тааруулж, давхардуулахгүйгээр lead болгоно. Энэ нь WEBHOOK-ИЙН ХАЛУУН
--      ЗАМД, live дамжуулалтын үеэр секундэд хэдэн удаа ажиллана.
--   2) `POST /api/dashboard/customers` — гараар лид нэмэхэд давхардлыг шалгана.
--
-- Хоёул `phone IN (...)` хэлбэрээр хайдаг (LIKE '%digits' биш — тэр нь эхэндээ
-- wildcard-тай тул индекс огт хэрэглэж чадахгүй бөгөөд "976-9911-2233" мэтийн
-- хадгалалттай таарахгүй). `customers`-д `phone` дээр ямар ч индекс байгаагүй.
--
-- Хэсэгчилсэн (partial) индекс: утасгүй мөрүүд орохгүй тул хэмжээ бага.
-- Шинэ хүснэгт / багана нэмэхгүй — зөвхөн индекс, тиймээс буцаах нь аюулгүй.

CREATE INDEX IF NOT EXISTS idx_customers_shop_phone
  ON public.customers (shop_id, phone)
  WHERE phone IS NOT NULL;

COMMENT ON INDEX public.idx_customers_shop_phone IS
  'Comment-lead → customer тааруулалт болон гараар лид нэмэх үеийн давхардлын шалгалт (shop_id + phone тэнцүү хайлт).';
